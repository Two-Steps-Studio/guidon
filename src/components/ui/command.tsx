"use client"

import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { Search } from "lucide-react"

import { cn } from "@/lib/utils"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogTitle,
} from "@/components/ui/dialog"

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "bg-popover text-popover-foreground flex h-full w-full flex-col overflow-hidden rounded-md",
        className
      )}
      {...props}
    />
  )
}

interface CommandDialogProps extends React.ComponentProps<typeof Dialog> {
  title?: string
  description?: string
  /** Forwarded to the inner Command root - false when the caller does its
   * own filtering (e.g. mixing server-side search results with local nav
   * items, where cmdk's default substring match against `value` would
   * hide a server-matched result whose title doesn't literally contain
   * the query). Defaults to cmdk's own default (true). */
  shouldFilter?: boolean
}

function CommandDialog({
  title = "Command palette",
  description = "Search and jump to anything",
  shouldFilter,
  children,
  ...props
}: CommandDialogProps) {
  return (
    <Dialog {...props}>
      {/* Radix Dialog requires a Title/Description for a11y even when the
          palette's own visible chrome doesn't need one - sr-only rather
          than omitted. */}
      <DialogTitle className="sr-only">{title}</DialogTitle>
      <DialogDescription className="sr-only">{description}</DialogDescription>
      <DialogContent
        showCloseButton={false}
        className="overflow-hidden p-0 shadow-lg sm:max-w-2xl"
      >
        <Command
          shouldFilter={shouldFilter}
          className="[&_[cmdk-group-heading]]:text-muted-foreground [&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group]:not([hidden])_~[cmdk-group]]:pt-0 [&_[cmdk-group]]:px-2 [&_[cmdk-input-wrapper]_svg]:h-5 [&_[cmdk-input-wrapper]_svg]:w-5 [&_[cmdk-input]]:h-12 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-3 [&_[cmdk-item]_svg]:h-5 [&_[cmdk-item]_svg]:w-5"
        >
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

