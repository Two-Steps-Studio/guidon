#!/usr/bin/env node
/**
 * Bring a database up to date when its migrations were applied by hand.
 *
 *   node scripts/db-catch-up.mjs --status [--out file]   SQL that lists which migrations are in place
 *   node scripts/db-catch-up.mjs [--out file]            SQL that applies only the missing ones
 *   DATABASE_URL=... node scripts/db-catch-up.mjs --verify   check the probes against a scratch database
 *
 * `npm run migrate` keeps a registry (guidon_migrations) and runs what it
 * hasn't recorded. A Supabase project maintained through the SQL editor has
 * no registry, so the runner would start again at 000 - wrong and unsafe.
 * The SQL generated here decides per migration from the schema itself
 * (src/db/migrations/probes.mjs), applies only what's missing, in order and
 * in ONE transaction (all or nothing), and then records every migration in
 * guidon_migrations with the same checksum the runner computes - from then
 * on `npm run migrate` works normally against that database.
 *
 * Paste the output into the Supabase SQL editor (or psql). Nothing here
 * connects to your database except --verify, which DROPS and recreates the
 * database named in DATABASE_URL - point it at a scratch one only.
 */

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MIGRATION_PROBES } from "../src/db/migrations/probes.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = path.join(HERE, "..", "src", "db", "migrations");
const BOOTSTRAP = path.join(HERE, "..", "src", "db", "bootstrap", "000_auth_compat.sql");

const args = process.argv.slice(2);
const outIndex = args.indexOf("--out");
const outFile = outIndex >= 0 ? args[outIndex + 1] : null;

function fail(message) {
  console.error(`\n  ${message}\n`);
  process.exit(1);
}

async function loadMigrations() {
  const names = (await readdir(MIGRATIONS_DIR)).filter((n) => /^\d{3}_.*\.sql$/.test(n)).sort();
  const missing = names.filter((n) => !MIGRATION_PROBES[n]);
  if (missing.length) fail(`No probe in src/db/migrations/probes.mjs for: ${missing.join(", ")}`);
  return Promise.all(
    names.map(async (name) => {
      const sql = await readFile(path.join(MIGRATIONS_DIR, name), "utf8");
      return {
        name,
        sql,
        // Same as scripts/migrate.mjs, so the registry rows written here match.
        checksum: createHash("sha256").update(sql).digest("hex").slice(0, 16),
        probe: MIGRATION_PROBES[name],
      };
    })
  );
}

const PROBE_FUNCTION = `CREATE OR REPLACE FUNCTION pg_temp.guidon_probe(sql text) RETURNS boolean LANGUAGE plpgsql AS $fn$
DECLARE r boolean;
BEGIN
  EXECUTE 'SELECT ' || sql INTO r;
  RETURN coalesce(r, false);
EXCEPTION WHEN OTHERS THEN
  -- A probe that refers to a table a later migration creates just means "not yet".
  RETURN false;
END $fn$;`;

function statusSql(migrations) {
  const rows = migrations.map((m) => `  ('${m.name}', $probe$${m.probe}$probe$)`).join(",\n");
  return `-- Guidon: which migrations are in this database. Read-only.\n${PROBE_FUNCTION}\n\nSELECT m.name AS migration, pg_temp.guidon_probe(m.probe) AS applied\nFROM (VALUES\n${rows}\n) AS m(name, probe)\nORDER BY m.name;\n`;
}

/** The file without its own BEGIN;/COMMIT; - the whole catch-up is one transaction. */
function body(sql) {
  return sql.replace(/^BEGIN;\s*$/m, "").replace(/^COMMIT;\s*$/m, "");
}

function catchUpSql(migrations) {
  const parts = [
    "-- Guidon: apply the migrations this database is missing, then record all of them.",
    "-- One transaction: if anything fails, nothing changes. Generated by scripts/db-catch-up.mjs.",
    "BEGIN;",
    "",
    PROBE_FUNCTION,
    "",
    `CREATE TABLE IF NOT EXISTS public.guidon_migrations (
    name        text PRIMARY KEY,
    checksum    text NOT NULL,
    applied_at  timestamptz NOT NULL DEFAULT now(),
    duration_ms integer
);`,
  ];
  for (const m of migrations) {
    const tag = `$mig_${m.name.slice(0, 3)}$`;
    if (m.sql.includes(tag)) fail(`${m.name} contains ${tag}; pick another quoting tag.`);
    parts.push(
      "",
      `-- ${m.name}`,
      `DO $run$ BEGIN
  IF NOT pg_temp.guidon_probe($probe$${m.probe}$probe$) THEN
    RAISE NOTICE 'Applying ${m.name}';
    EXECUTE ${tag}${body(m.sql)}${tag};
  END IF;
  INSERT INTO public.guidon_migrations (name, checksum, duration_ms)
  VALUES ('${m.name}', '${m.checksum}', 0)
  ON CONFLICT (name) DO NOTHING;
END $run$;`
    );
  }
  parts.push("", "COMMIT;", "");
  return parts.join("\n");
}

async function verify(migrations) {
  const url = process.env.DATABASE_URL;
  if (!url) fail("--verify needs DATABASE_URL pointing at a scratch database (it is dropped and recreated).");
  const pg = (await import("pg")).default;
  const target = new URL(url);
  const dbName = target.pathname.slice(1);
  const admin = new pg.Client({ connectionString: Object.assign(new URL(url), { pathname: "/postgres" }).toString() });
  await admin.connect();
  await admin.query(`DROP DATABASE IF EXISTS "${dbName}"`);
  await admin.query(`CREATE DATABASE "${dbName}"`);
  await admin.end();

  const client = new pg.Client({ connectionString: url });
  await client.connect();
  await client.query(await readFile(BOOTSTRAP, "utf8"));
  await client.query(PROBE_FUNCTION);
  const check = async (applied) => {
    const bad = [];
    for (const m of migrations) {
      const { rows } = await client.query("SELECT pg_temp.guidon_probe($1) AS ok", [m.probe]);
      const expected = Number(m.name.slice(0, 3)) <= applied;
      // 038/052 only re-assert state and are safe to re-run - see probes.mjs.
      if (rows[0].ok !== expected && !/^(038|052)_/.test(m.name)) bad.push(`${m.name.slice(0, 3)}=${rows[0].ok}`);
    }
    return bad;
  };
  let problems = 0;
  for (const [i, m] of [[-1, null], ...migrations.map((m) => [Number(m.name.slice(0, 3)), m])]) {
    if (m) await client.query(m.sql);
    const bad = await check(i);
    if (bad.length) {
      problems++;
      console.log(`  after ${m ? m.name : "nothing"}: ${bad.join(" ")}`);
    }
  }
  await client.end();
  if (problems) fail("Probes disagree with the chain - fix src/db/migrations/probes.mjs.");
  console.log(`  ${migrations.length} probes match the migration chain step by step.`);
}

const migrations = await loadMigrations();
if (args.includes("--verify")) {
  await verify(migrations);
} else {
  const sql = args.includes("--status") ? statusSql(migrations) : catchUpSql(migrations);
  if (outFile) {
    await writeFile(outFile, sql);
    console.error(`  Wrote ${outFile}`);
  } else {
    process.stdout.write(sql);
  }
}
